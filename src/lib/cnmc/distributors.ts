export function getCupsDistributorPrefix(cups: string): string | null {
    const normalized = normalizeCups(cups);
    const match = /^ES(\d{4})/.exec(normalized);
    return match ? `ES${match[1]}` : null;
}

/**
 * Nombre de la distribuidora de un CUPS, o `null` si el prefijo no consta.
 *
 * Devolver `null` es deliberado: la tabla no cubre todos los prefijos posibles
 * y aparecen distribuidoras nuevas. Es preferible no mostrar nada a mostrar una
 * distribuidora equivocada en una propuesta.
 */
export function getDistributorForCups(cups: string): string | null {
    const prefix = getCupsDistributorPrefix(cups);
    return prefix ? DISTRIBUTORS_BY_CUPS_PREFIX[prefix] ?? null : null;
}