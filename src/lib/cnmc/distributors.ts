/**
 * Misma normalización que `normalizeCups` de `./sips`, repetida aquí a
 * propósito: `sips.ts` importa `node:crypto` para firmar OAuth contra la CNMC,
 * y este módulo se usa desde componentes de cliente. Importarlo arrastraría
 * `node:crypto` al bundle del navegador.
 */
function normalizeCups(cups: string): string {
    return cups.trim().toUpperCase().replace(/\s+/g, '');
}

